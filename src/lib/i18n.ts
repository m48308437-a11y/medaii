const dictionaries: Record<Locale, Dict> = { fa, en, de };

export function getTranslation(locale: Locale = defaultLocale) {
  const dict = dictionaries[locale] || dictionaries[defaultLocale];
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = dict[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`{${k}}`, "g"), String(v));
      }
    }
    return text;
  };
}

export function getLocaleFromHeaders(acceptLanguage?: string): Locale {
  if (!acceptLanguage) return defaultLocale;
  if (acceptLanguage.includes("fa") || acceptLanguage.includes("per")) return "fa";
  if (acceptLanguage.includes("de")) return "de";
  if (acceptLanguage.includes("en")) return "en";
  return defaultLocale;
}
